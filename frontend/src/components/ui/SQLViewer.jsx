import React, { useState } from 'react';
import { Copy, Check, ChevronDown, ChevronUp, Cpu } from 'lucide-react';
import Button from './Button';

const SQLViewer = ({ sql, className = '' }) => {
  const [copied, setCopied] = useState(false);
  const [isCollapsed, setIsCollapsed] = useState(false);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(sql);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch (err) {
      console.error('Failed to copy text', err);
    }
  };

  return (
    <div className={`flex flex-col border border-light-border dark:border-dark-border rounded-xl overflow-hidden bg-slate-900 text-slate-100 ${className}`}>
      {/* Header */}
      <div className="flex items-center justify-between px-4 py-2.5 bg-slate-950 border-b border-slate-800">
        <div className="flex items-center gap-2 text-xs font-semibold text-accent-secondary">
          <Cpu size={14} className="animate-pulse" />
          <span>GENERATED BY ASKDB AI</span>
        </div>
        <div className="flex items-center gap-1.5">
          <Button
            variant="ghost"
            size="sm"
            onClick={() => setIsCollapsed(!isCollapsed)}
            className="!p-1.5 hover:!bg-slate-850 !text-slate-400 focus:ring-0 focus:ring-offset-0"
          >
            {isCollapsed ? <ChevronDown size={14} /> : <ChevronUp size={14} />}
          </Button>
          <Button
            variant="ghost"
            size="sm"
            onClick={handleCopy}
            className="!p-1.5 hover:!bg-slate-850 !text-slate-400 focus:ring-0 focus:ring-offset-0 flex items-center gap-1"
          >
            {copied ? (
              <>
                <Check size={14} className="text-accent-success" />
                <span className="text-[10px] text-accent-success font-medium">Copied!</span>
              </>
            ) : (
              <Copy size={14} />
            )}
          </Button>
        </div>
      </div>

      {/* Code body */}
      {!isCollapsed && (
        <pre className="p-4 overflow-x-auto font-mono text-xs leading-relaxed text-indigo-200 bg-slate-900 max-h-[300px]">
          <code>
            {sql.split('\n').map((line, idx) => {
              // Simple syntax highlighting representation
              const highlightKeywords = (text) => {
                const keywords = [
                  'SELECT', 'FROM', 'JOIN', 'ON', 'WHERE', 'GROUP BY', 
                  'ORDER BY', 'LIMIT', 'SUM', 'COUNT', 'AVG', 'AND', 
                  'OR', 'LEFT JOIN', 'RIGHT JOIN', 'INNER JOIN', 'AS', 'DESC', 'ASC'
                ];
                let html = text;
                keywords.forEach((keyword) => {
                  const regex = new RegExp(`\\b${keyword}\\b`, 'g');
                  html = html.replace(regex, `<span class="text-amber-400 font-bold">${keyword}</span>`);
                });
                return html;
              };

              return (
                <div key={idx} className="table-row">
                  <span className="table-cell select-none pr-3 text-slate-600 text-right w-6 text-[10px]">{idx + 1}</span>
                  <span className="table-cell" dangerouslySetInnerHTML={{ __html: highlightKeywords(line) }} />
                </div>
              );
            })}
          </code>
        </pre>
      )}
    </div>
  );
};

export default SQLViewer;
